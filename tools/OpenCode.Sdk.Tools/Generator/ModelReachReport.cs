using System.Text;
using OpenCode.Sdk.Tools.Generator.Binding.Models;

namespace OpenCode.Sdk.Tools.Generator;

/// <summary>
/// The committed reach report: one line per placed type (models, union interfaces and their kits,
/// hoisted interfaces) with the slice that owns its folder and every family whose operations reach
/// it; an empty list means no selected operation reaches it. A refresh that widens a type's reach
/// shows as a one-line diff here; the folder never follows reach.
/// </summary>
internal sealed record ModelReachReport
{
    public const string Header =
        "# Generated by OpenCode.Sdk.Tools from the bound plan.\n"
        + "# Each line: a model, the slice that owns its folder, and the families whose operations reach it. Reach never moves a file.\n";

    public required string Content { get; init; }

    /// <summary>Gets the number of models some family other than their owner reaches, or that their owner does not reach.</summary>
    public required int ReachedBeyondOwner { get; init; }

    public static ModelReachReport Compose(ModelPlacement placement, IReadOnlyDictionary<string, IReadOnlyList<string>> reach)
    {
        ArgumentNullException.ThrowIfNull(placement);
        ArgumentNullException.ThrowIfNull(reach);

        var content = new StringBuilder(Header);
        var beyondOwner = 0;
        foreach (var (typeName, home) in placement.Homes.OrderBy(static entry => entry.Key, StringComparer.Ordinal))
        {
            var owner = home.Slice;
            var families = reach.TryGetValue(typeName, out var reachedBy) ? reachedBy : [];
            if (families.Count is not 1 || !string.Equals(families[0], owner, StringComparison.Ordinal))
            {
                beyondOwner++;
            }

            _ = content.Append(typeName).Append(" owner=").Append(owner).Append(" reached-by=").AppendJoin(',', families).Append('\n');
        }

        return new ModelReachReport { Content = content.ToString(), ReachedBeyondOwner = beyondOwner };
    }
}
