using System.IO.Abstractions;
using System.Text;
using System.Text.Json;
using OpenCode.Sdk.Tools.Generator.Emission;
using OpenCode.Sdk.Tools.Serialization;

namespace OpenCode.Sdk.Tools.Output;

/// <summary>Reads ownership, checks provenance and renders the canonical generated metadata.</summary>
internal sealed class ManifestStore(IFileSystem fileSystem, PlacementValidator placement)
{
    internal const string ManifestRelativePath = ".generated-manifest.json";
    internal const string MarkerRelativePath = ".generation-incomplete";
    internal const string AttributesRelativePath = ".gitattributes";
    internal const string ReachRelativePath = ".generated-reach.txt";
    private const string AttributesHeader =
        "# Generated by OpenCode.Sdk.Tools from the generation manifest.\n"
        + "# Do not edit by hand: it marks every generated file linguist-generated; regenerate instead.\n";
    private readonly IFileSystem _fileSystem = fileSystem ?? throw new ArgumentNullException(nameof(fileSystem));
    private readonly PlacementValidator _placement = placement ?? throw new ArgumentNullException(nameof(placement));

    public async Task<IReadOnlySet<string>> LoadAsync(string outputRoot, CancellationToken cancellationToken)
    {
        var path = _placement.ResolveOwnedPath(outputRoot, ManifestRelativePath);
        if (!_fileSystem.File.Exists(path))
        {
            return new HashSet<string>(PlacementValidator.OwnedPathComparer);
        }

        GenerationManifest manifest;
        try
        {
            var json = await _fileSystem.File.ReadAllTextAsync(path, cancellationToken).ConfigureAwait(false);
            manifest = JsonSerializer.Deserialize(json, ToolJsonContext.Default.GenerationManifest)
                       ?? throw new OutputRefusalException("The generation manifest cannot be JSON null.");
        }
        catch (JsonException exception)
        {
            throw new OutputRefusalException("The generation manifest is invalid.", exception);
        }

        var result = new HashSet<string>(PlacementValidator.OwnedPathComparer);
        foreach (var relativePath in manifest.Files)
        {
            _ = _placement.ResolveOwnedPath(outputRoot, relativePath);
            PlacementValidator.ValidateManifestSourcePath(relativePath);
            if (!result.Add(relativePath))
            {
                throw new OutputRefusalException($"Generation manifest path '{relativePath}' is duplicated.");
            }
        }

        return result;
    }

    public async Task RequireProvenanceAsync(string outputRoot, IReadOnlySet<string> oldPaths, CancellationToken cancellationToken)
    {
        foreach (var relativePath in oldPaths.Order(StringComparer.Ordinal))
        {
            var path = _placement.ResolveOwnedPath(outputRoot, relativePath);
            // A previous write may have claimed a path before installing it, or already deleted it.
            if (!_fileSystem.File.Exists(path))
            {
                continue;
            }

            var content = await _fileSystem.File.ReadAllTextAsync(path, cancellationToken).ConfigureAwait(false);
            if (!GenerationProvenance.HasHeader(content))
            {
                throw new OutputRefusalException(
                    $"Manifest entry '{relativePath}' does not carry the provenance header; refusing to overwrite or delete it.");
            }
        }

        // An attributes file the writer did not write belongs to somebody else; refuse to replace it.
        var attributesPath = _placement.ResolveOwnedPath(outputRoot, AttributesRelativePath);
        if (_fileSystem.File.Exists(attributesPath))
        {
            var content = await _fileSystem.File.ReadAllTextAsync(attributesPath, cancellationToken).ConfigureAwait(false);
            if (!content.ReplaceLineEndings("\n").StartsWith(AttributesHeader, StringComparison.Ordinal))
            {
                throw new OutputRefusalException($"'{AttributesRelativePath}' does not carry the generated header; refusing to overwrite it.");
            }
        }
    }

    public static byte[] ManifestBytes(IEnumerable<string> paths, IReadOnlyDictionary<string, string> implicitAliases)
    {
        var manifest = new GenerationManifest
        {
            Files = [.. paths.Order(StringComparer.Ordinal)],
            ImplicitAliases = implicitAliases,
        };
        return Encoding.UTF8.GetBytes($"{JsonSerializer.Serialize(manifest, ToolJsonContext.Default.GenerationManifest)}\n");
    }

    /// <summary>
    /// Marks every generated file linguist-generated so hosted trees and diffs distinguish it
    /// from hand-written files sharing the same folders.
    /// </summary>
    public static KeyValuePair<string, byte[]?>[] Metadata(GenerationWriteRequest request, IEnumerable<string> paths)
    {
        var attributes = new StringBuilder(AttributesHeader);
        foreach (var path in paths.Order(StringComparer.Ordinal))
        {
            _ = attributes.Append('/').Append(path).Append(" linguist-generated\n");
        }

        return
        [
            new(MarkerRelativePath, request.PartialMarkerContent is { } marker ? Encoding.UTF8.GetBytes(marker) : null),
            new(AttributesRelativePath, Encoding.UTF8.GetBytes(attributes.ToString())),
            new(ReachRelativePath, request.ReachReportContent is { } reach ? Encoding.UTF8.GetBytes(reach) : null),
        ];
    }
}
