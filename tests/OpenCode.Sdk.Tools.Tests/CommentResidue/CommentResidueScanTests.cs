using OpenCode.Sdk.Tools.Tests.CommentResidue.Support;

namespace OpenCode.Sdk.Tools.Tests.CommentResidue;

/// <summary>Each residue rule, in each comment form the gate reads, and what it leaves alone.</summary>
public sealed class CommentResidueScanTests
{
    private const string Source = "src/A.cs";
    private const string Type = "internal sealed class A;";
    private const string GuidePath = "docs/guide/a.md";

    [Test]
    public async Task Scan_Should_Report_A_Task_Number_In_A_Line_Comment()
    {
        var hits = await new CommentResidueScenario()
            .WithFile(Source, "// The guard Task 5 added.", Type)
            .ScanAsync();

        await Assert.That(hits).IsEquivalentTo([$"{Source}:1: {CommentResidueScan.TaskNumber}: 'Task 5'"]);
    }

    [Test]
    public async Task Scan_Should_Report_A_Design_Section_On_The_Line_Of_A_Documentation_Comment()
    {
        var hits = await new CommentResidueScenario()
            .WithFile(Source, "/// <summary>", "/// The fixture (design §7.2).", "/// </summary>", Type)
            .ScanAsync();

        await Assert.That(hits).IsEquivalentTo([$"{Source}:2: {CommentResidueScan.DesignSection}: 'design §'"]);
    }

    [Test]
    public async Task Scan_Should_Report_A_Line_Comment_In_An_Inactive_Region()
    {
        var hits = await new CommentResidueScenario()
            .WithFile(Source, "#if NEVER_DEFINED", "// research log Q157", "#endif", Type)
            .ScanAsync();

        await Assert.That(hits).IsEquivalentTo([$"{Source}:2: {CommentResidueScan.ResearchLogNumber}: 'Q157'"]);
    }

    [Test]
    public async Task Scan_Should_Leave_The_Same_Text_In_A_String_Alone()
    {
        var hits = await new CommentResidueScenario()
            .WithFile(Source, "internal sealed class A", "{", $"    public const string Text = \"// Task 5, design §7.2, Q157, {GuidePath}\";", "}")
            .ScanAsync();

        await Assert.That(hits).IsEmpty();
    }

    [Test]
    public async Task Scan_Should_Report_A_Documentation_Path_In_A_Project_File_Comment()
    {
        var hits = await new CommentResidueScenario()
            .WithFile("src/A.csproj", "<Project>", $"  <!-- See {GuidePath}. -->", "</Project>")
            .ScanAsync();

        await Assert.That(hits).IsEquivalentTo([$"src/A.csproj:2: {CommentResidueScan.DocumentationPath}: '{GuidePath}'"]);
    }

    [Test]
    public async Task Scan_Should_Report_A_Research_Log_Number_In_A_Workflow_Comment()
    {
        var hits = await new CommentResidueScenario()
            .WithFile(".github/workflows/ci.yml", "jobs:", "  build: # measured in Q172", "    runs-on: ubuntu-latest")
            .ScanAsync();

        await Assert.That(hits).IsEquivalentTo([$".github/workflows/ci.yml:2: {CommentResidueScan.ResearchLogNumber}: 'Q172'"]);
    }

    [Test]
    public async Task Scan_Should_Report_A_Documentation_Path_In_A_Script_Block_Comment()
    {
        var hits = await new CommentResidueScenario()
            .WithFile("tests/Fixtures/peer.js", "const url = 'https://example.test/a';", "/*", $" * Mirrors {GuidePath}.", " */")
            .ScanAsync();

        await Assert.That(hits).IsEquivalentTo([$"tests/Fixtures/peer.js:3: {CommentResidueScan.DocumentationPath}: '{GuidePath}'"]);
    }

    [Test]
    public async Task Scan_Should_Leave_Generated_Files_Markdown_And_Json_Alone()
    {
        var hits = await new CommentResidueScenario()
            .WithFile("src/Models/B.cs", "// Generated by OpenCode.Sdk.Tools from spec/openapi.json.", "// Task 5", "internal sealed class B;")
            .WithFile("docs/guide/README.md", "Task 5, design §7.2")
            .WithFile("tools/curation.json", "{ \"reason\": \"Task 5\" }")
            .ScanAsync();

        await Assert.That(hits).IsEmpty();
    }

    [Test]
    public async Task Scan_Should_Report_A_Snapshot_Auto_Accept_In_Code_And_In_A_Workflow()
    {
        var hits = await new CommentResidueScenario()
            .WithFile(Source, "internal static class A", "{", "    public static void Initialize() => VerifierSettings.AutoVerify();", "}")
            .WithFile(".github/workflows/ci.yml", "env:", "  Verify_AutoVerify: true")
            .ScanAsync();

        await Assert.That(hits).IsEquivalentTo(
        [
            $"{Source}:3: {CommentResidueScan.SnapshotAutoAccept}: 'AutoVerify'",
            $".github/workflows/ci.yml:2: {CommentResidueScan.SnapshotAutoAccept}: 'Verify_AutoVerify: true'",
        ]);
    }

    [Test]
    public async Task Scan_Should_Report_A_Stryker_Suppression_Only_Without_A_Reason()
    {
        var hits = await new CommentResidueScenario()
            .WithFile(Source, "// Stryker disable once Equality", "// Stryker disable once Boolean : the flag is a constant", Type)
            .ScanAsync();

        await Assert.That(hits).IsEquivalentTo([$"{Source}:1: {CommentResidueScan.UnexplainedStrykerDisable}: '// Stryker disable once Equality'"]);
    }
}
