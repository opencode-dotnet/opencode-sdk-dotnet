using System.IO.Abstractions;
using System.Text;
using System.Text.Json;
using OpenCode.Sdk.Tools.Output;
using OpenCode.Sdk.Tools.Output.Abstractions;
using OpenCode.Sdk.Tools.Tests.Support;
using Testably.Abstractions.Testing;
using TUnit.Assertions.Enums;

namespace OpenCode.Sdk.Tools.Tests.Output;

public sealed class StagedWriteTests
{
    private const string Manifest = ".generated-manifest.json";
    private const string Marker = ".generation-incomplete";
    private const string Attributes = ".gitattributes";
    private const string Reach = ".generated-reach.txt";
    private const string AttributesHeader =
        "# Generated by OpenCode.Sdk.Tools from the generation manifest.\n"
        + "# Do not edit by hand: it marks every generated file linguist-generated; regenerate instead.\n";
    private static readonly string[] NewPaths = ["A.cs", "B.cs", "C.cs", "D.cs"];
    private static readonly string[] OldPaths = ["A.cs", "Retired.cs", "Stale.cs"];

    [Test]
    [Arguments("union", 0, false)]
    [Arguments("source", 0, false)]
    [Arguments("source", 1, false)]
    [Arguments("source", 2, false)]
    [Arguments("source", 4, false)]
    [Arguments("stale", 0, false)]
    [Arguments("format-before", 0, false)]
    [Arguments("format-during", 0, false)]
    [Arguments(Marker, 0, false)]
    [Arguments(Attributes, 0, false)]
    [Arguments(Reach, 0, false)]
    [Arguments("final", 0, false)]
    [Arguments("source-content", 0, false)]
    [Arguments("manifest-content", 0, false)]
    [Arguments("source", 2, true)]
    public async Task WriteAsync_Should_Recover_An_Interrupted_Generation(string phase, int installed, bool differentRequest)
    {
        var fs = GenerationTestData.CreateFileSystem();
        await SeedAsync(fs, phase == "manifest-content");
        var request = Request(NewPaths);
        await InterruptAsync(fs, request, phase, installed);

        var mixed = await ReadTreeAsync(fs);
        var verificationFs = await CopyTreeAsync(mixed);
        var verify = await Writer(verificationFs, Formatter(verificationFs))
            .WriteAsync(request with { Verify = true }, CancellationToken.None);
        await Assert.That(verify.HasChanges).IsTrue();
        if (phase == "manifest-content")
        {
            await Assert.That(mixed.Keys).DoesNotContain(Manifest);
        }
        else
        {
            var ownership = JsonSerializer.Deserialize<GenerationManifest>(Encoding.UTF8.GetString(mixed[Manifest]));
            await Assert.That(ownership!.Files).IsEquivalentTo(
                OldPaths.Union(NewPaths, StringComparer.Ordinal).Order(StringComparer.Ordinal), CollectionOrdering.Matching);
        }

        var next = differentRequest ? Request(["B.cs", "E.cs"]) with { PartialMarkerContent = null, ReachReportContent = null } : request;
        _ = await Writer(fs, Formatter(fs)).WriteAsync(next, CancellationToken.None);
        var expected = Expected(next);
        var actual = await ReadTreeAsync(fs);
        await Assert.That(actual.Keys.Order(StringComparer.Ordinal))
            .IsEquivalentTo(expected.Keys.Order(StringComparer.Ordinal), CollectionOrdering.Matching);
        foreach (var (path, bytes) in expected)
        {
            await Assert.That(actual[path]).IsEquivalentTo(bytes, CollectionOrdering.Matching);
        }

        var clean = await Writer(fs, Formatter(fs)).WriteAsync(next, CancellationToken.None);
        await Assert.That(clean.HasChanges).IsFalse();
    }

    [Test]
    public async Task WriteAsync_Should_Install_And_Format_Sources_In_Ordinal_Order()
    {
        var fs = GenerationTestData.CreateFileSystem();
        var installed = new List<string>();
        var formatter = new RecordingProjectFormatter(fs);
        using (fs.Notify.OnEvent(change =>
        {
            var name = fs.Path.GetFileName(change.Path);
            if (change.ChangeType == WatcherChangeTypes.Renamed && name.EndsWith(".cs", StringComparison.Ordinal))
            {
                installed.Add(name);
            }
        }))
        {
            _ = await Writer(fs, formatter).WriteAsync(Request(["b.cs", "A.cs"]), CancellationToken.None);
        }

        await Assert.That(installed).IsEquivalentTo(["A.cs", "b.cs"], CollectionOrdering.Matching);
        await Assert.That(formatter.SourcePaths).IsEquivalentTo(["A.cs", "b.cs"], CollectionOrdering.Matching);
    }

    private static async Task InterruptAsync(MockFileSystem fs, GenerationWriteRequest request, string phase, int installed)
    {
        var written = new HashSet<string>(StringComparer.Ordinal);
        var published = false;
        var deleted = false;
        using (fs.Notify.OnEvent(change =>
        {
            var name = fs.Path.GetFileName(change.Path);
            if (change.ChangeType is WatcherChangeTypes.Changed or WatcherChangeTypes.Renamed)
            {
                _ = written.Add(name);
                published |= name == Manifest;
            }

            deleted |= change.ChangeType == WatcherChangeTypes.Deleted && name == "Retired.cs";
        }))
        using (fs.Intercept.Event(change =>
        {
            var name = fs.Path.GetFileName(change.Path);
            if (change.FileSystemType != FileSystemTypes.File
                || (change.ChangeType == WatcherChangeTypes.Deleted && name.EndsWith(".tmp", StringComparison.Ordinal)))
            {
                return;
            }

            var stop = phase switch
            {
                "union" => published,
                "source" when installed == 0 => change.ChangeType == WatcherChangeTypes.Changed
                    && name.StartsWith("A.cs", StringComparison.Ordinal),
                "source" => NewPaths.Count(written.Contains) == installed,
                "stale" => deleted,
                "source-content" => change.ChangeType == WatcherChangeTypes.Changed
                    && name.StartsWith("B.cs", StringComparison.Ordinal),
                "manifest-content" => change.ChangeType == WatcherChangeTypes.Changed
                    && name.StartsWith(Manifest, StringComparison.Ordinal),
                Marker or Attributes or Reach => change.ChangeType == WatcherChangeTypes.Changed
                    && name.StartsWith(phase, StringComparison.Ordinal),
                "final" => published && name.StartsWith(Manifest, StringComparison.Ordinal),
                _ => false,
            };
            if (stop)
            {
                throw new IOException(phase);
            }
        }))
        {
            var failure = await Assert.That(async () => _ = await Writer(fs, Formatter(fs, phase)).WriteAsync(request, CancellationToken.None))
                .Throws<IOException>();
            await Assert.That(failure!.Message).IsEqualTo(phase);
        }
    }

    private static GenerationWriter Writer(IFileSystem fs, IProjectFormatter formatter)
    {
        var placement = new PlacementValidator(fs);
        return new GenerationWriter(fs, placement, new ManifestStore(fs, placement), new StagedWrite(fs, placement, formatter));
    }

    private static GenerationWriteRequest Request(IReadOnlyList<string> paths) => new()
    {
        OutputRoot = GenerationTestData.OutputRoot,
        ProjectPath = GenerationTestData.ProjectPath,
        Sources = [.. paths.Select(path => GenerationTestData.Source(path, $"raw {path}\n"))],
        FamilyFolders = [],
        ImplicitAliases = new Dictionary<string, string>(StringComparer.Ordinal) { ["Alias_1"] = "Alias" },
        PartialMarkerContent = "pending\n",
        ReachReportContent = GenerationTestData.ReachReport,
        Verify = false,
    };

    private static async Task SeedAsync(MockFileSystem fs, bool freshManifest)
    {
        await fs.File.WriteAllTextAsync(FullPath(fs, "Manual.cs"), "manual\n");
        if (freshManifest)
        {
            return;
        }

        foreach (var path in OldPaths)
        {
            await fs.File.WriteAllTextAsync(FullPath(fs, path), GenerationTestData.OwnedContent($"old {path}\n"));
        }

        await fs.File.WriteAllTextAsync(FullPath(fs, Manifest), JsonSerializer.Serialize(new GenerationManifest { Files = OldPaths }));
        await fs.File.WriteAllTextAsync(FullPath(fs, Attributes), AttributesHeader);
        await fs.File.WriteAllTextAsync(FullPath(fs, Marker), "old pending\n");
        await fs.File.WriteAllTextAsync(FullPath(fs, Reach), GenerationTestData.StaleReachReport);
    }

    private static RecordingProjectFormatter Formatter(MockFileSystem fs, string? phase = null) =>
        new(fs, async (current, project, paths, token) =>
        {
            await Assert.That(project).IsEqualTo(GenerationTestData.ProjectPath);
            await Assert.That(paths).IsEquivalentTo(paths.Order(StringComparer.Ordinal), CollectionOrdering.Matching);
            if (phase == "format-before")
            {
                throw new IOException(phase);
            }

            foreach (var path in paths)
            {
                var full = FullPath(current, path);
                var text = await current.File.ReadAllTextAsync(full, token);
                await current.File.WriteAllTextAsync(full, text.Replace("raw ", "formatted ", StringComparison.Ordinal), token);
                if (phase == "format-during")
                {
                    throw new IOException(phase);
                }
            }
        });

    private static Dictionary<string, byte[]> Expected(GenerationWriteRequest request)
    {
        var paths = request.Sources.Select(static source => source.RelativePath).Order(StringComparer.Ordinal).ToArray();
        var files = paths.ToDictionary(static path => path,
            static path => Encoding.UTF8.GetBytes(GenerationTestData.OwnedContent($"formatted {path}\n")), StringComparer.Ordinal);
        // The independent oracle pins the canonical layout, aliases, ordering, UTF-8 and final newline.
        files[Manifest] = Encoding.UTF8.GetBytes("{\n  \"files\": [\n"
            + string.Join(",\n", paths.Select(static path => $"    \"{path}\""))
            + "\n  ],\n  \"implicitAliases\": {\n    \"Alias_1\": \"Alias\"\n  }\n}\n");
        files[Attributes] = Encoding.UTF8.GetBytes(AttributesHeader + string.Concat(paths.Select(static path => $"/{path} linguist-generated\n")));
        files["Manual.cs"] = "manual\n"u8.ToArray();
        files["OpenCode.Sdk.csproj"] = "<Project />"u8.ToArray();
        if (request.PartialMarkerContent is { } marker)
        {
            files[Marker] = Encoding.UTF8.GetBytes(marker);
        }

        if (request.ReachReportContent is { } reach)
        {
            files[Reach] = Encoding.UTF8.GetBytes(reach);
        }

        return files;
    }

    private static async Task<Dictionary<string, byte[]>> ReadTreeAsync(MockFileSystem fs)
    {
        var files = new Dictionary<string, byte[]>(StringComparer.Ordinal);
        foreach (var path in fs.Directory.EnumerateFiles(GenerationTestData.OutputRoot, "*", SearchOption.AllDirectories))
        {
            files.Add(fs.Path.GetRelativePath(GenerationTestData.OutputRoot, path).Replace('\\', '/'), await fs.File.ReadAllBytesAsync(path));
        }

        return files;
    }

    private static async Task<MockFileSystem> CopyTreeAsync(IReadOnlyDictionary<string, byte[]> files)
    {
        var fs = GenerationTestData.CreateFileSystem();
        foreach (var (path, bytes) in files)
        {
            var target = FullPath(fs, path);
            fs.Directory.CreateDirectory(fs.Path.GetDirectoryName(target)!);
            await fs.File.WriteAllBytesAsync(target, bytes);
        }

        return fs;
    }

    private static string FullPath(IFileSystem fs, string path) => fs.Path.Combine(GenerationTestData.OutputRoot, path);
}
