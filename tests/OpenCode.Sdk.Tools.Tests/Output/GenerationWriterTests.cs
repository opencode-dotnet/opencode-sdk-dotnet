        _ = await writer.WriteAsync(Request([], reachReportContent: GenerationTestData.ReachReport), CancellationToken.None);

        var result = await writer.WriteAsync(Request([]), CancellationToken.None);

        await Assert.That(result.DeletedPaths).Contains(ReachReportName);
        await Assert.That(fileSystem.File.Exists(ReachPath)).IsFalse();
    }

    [Test]
    public async Task WriteAsync_Should_Move_Legacy_Sources_Into_The_Family_Layout()
    {
        const string legacyModel = "Models/A.cs";
        const string legacyAdapter = "Internal/ResponseAdapters/B.cs";
        const string familyModel = "Example/Models/A.cs";
        const string familyAdapter = "Example/Internal/B.cs";
        var fileSystem = GenerationTestData.CreateFileSystem();
        var manifest = JsonSerializer.Serialize(new GenerationManifest { Files = [legacyModel, legacyAdapter], });
        fileSystem.Initialize().With(
            new FileDescription(GenerationTestData.ManifestPath, manifest),
            new FileDescription(OwnedPath(fileSystem, legacyModel), GenerationTestData.OwnedContent("model")),
            new FileDescription(OwnedPath(fileSystem, legacyAdapter), GenerationTestData.OwnedContent("adapter")));
        var writer = CreateWriter(fileSystem);
        var request = Request(
            [GenerationTestData.Source(familyModel, "model"), GenerationTestData.Source(familyAdapter, "adapter")],
            familyFolders: ["Example"]);

        var move = await writer.WriteAsync(request, CancellationToken.None);
        var rerun = await writer.WriteAsync(request, CancellationToken.None);

        await Assert.That(move.DeletedPaths).IsEquivalentTo([legacyAdapter, legacyModel]);
        await Assert.That(fileSystem.File.Exists(OwnedPath(fileSystem, legacyModel))).IsFalse();
        await Assert.That(fileSystem.File.Exists(OwnedPath(fileSystem, legacyAdapter))).IsFalse();
        await Assert.That(fileSystem.File.Exists(OwnedPath(fileSystem, familyModel))).IsTrue();
        await Assert.That(fileSystem.File.Exists(OwnedPath(fileSystem, familyAdapter))).IsTrue();
        var written = JsonSerializer.Deserialize(
            await fileSystem.File.ReadAllTextAsync(GenerationTestData.ManifestPath, CancellationToken.None),
            ToolJsonContext.Default.GenerationManifest);
        await Assert.That(written!.Files).IsEquivalentTo([familyAdapter, familyModel]);
        await Assert.That(rerun.HasChanges).IsFalse();
    }

    /// <summary>Assembles one write request over the shared test roots; flags default off.</summary>
    private static GenerationWriteRequest Request(IReadOnlyList<GeneratedSource> sources,
        IReadOnlyList<string>? familyFolders = null, string? partialMarkerContent = null, bool verify = false,
        IReadOnlyDictionary<string, string>? implicitAliases = null, IReadOnlyList<string>? modelAreaFolders = null,
        string? reachReportContent = null) =>
        new()
        {
            OutputRoot = GenerationTestData.OutputRoot,
            ProjectPath = GenerationTestData.ProjectPath,
            Sources = sources,
            FamilyFolders = familyFolders ?? [],
            ModelAreaFolders = modelAreaFolders ?? [],
            PartialMarkerContent = partialMarkerContent,
            ReachReportContent = reachReportContent,
            ImplicitAliases = implicitAliases ?? new Dictionary<string, string>(StringComparer.Ordinal),
            Verify = verify,
        };

    private static GenerationWriter CreateWriter(MockFileSystem fileSystem) =>
        new(fileSystem, new RecordingProjectFormatter(fileSystem));

    private static string OwnedPath(MockFileSystem fileSystem, string relativePath) =>
        fileSystem.Path.Combine(GenerationTestData.OutputRoot, relativePath);

    /// <summary>The attributes file the writer owns: its header, then one line per path in the order given.</summary>
    private static string ExpectedAttributes(IReadOnlyList<string> orderedPaths) =>
        string.Concat(orderedPaths.Select(static path => $"/{path} linguist-generated\n").Prepend(AttributesHeader));
